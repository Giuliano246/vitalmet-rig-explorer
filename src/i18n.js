let lang = 'es';
const listeners = new Set();

export const getLang = () => lang;
export const languages = ['es', 'en'];

export function t(key, vars) {
  let s = dict[lang][key] ?? dict.es[key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replace(new RegExp(`\\{${k}\\}`, 'g'), String(v));
  return s;
}
// Texto de un objeto {es, en}; acepta strings y arrays.
export function L(obj) {
  if (obj == null) return '';
  if (typeof obj === 'string' || Array.isArray(obj)) return obj;
  return obj[lang] ?? obj.es ?? obj.en ?? '';
}

export function applyDom(root = document) {
  root.querySelectorAll('[data-i18n]').forEach((el) => { el.textContent = t(el.dataset.i18n); });
  root.querySelectorAll('[data-i18n-attr]').forEach((el) => {
    for (const pair of el.dataset.i18nAttr.split(',')) {
      const [attr, key] = pair.split(':').map((s) => s.trim());
      if (attr && key) el.setAttribute(attr, t(key));
    }
  });
  document.documentElement.lang = lang;
  document.title = t('app.title');
}

export function setLang(l) {
  if (!languages.includes(l) || l === lang) return;
  lang = l;
  try { localStorage.setItem('vitalmet.rig.lang', l); } catch { /* sin almacenamiento */ }
  applyDom();
  listeners.forEach((fn) => fn(l));
}
export const onLangChange = (fn) => { listeners.add(fn); return () => listeners.delete(fn); };

export function initLang() {
  let stored = null;
  try { stored = localStorage.getItem('vitalmet.rig.lang'); } catch { /* sin almacenamiento */ }
  const fromUrl = new URLSearchParams(location.search).get('lang');
  const pick = fromUrl || stored || (navigator.language?.toLowerCase().startsWith('en') ? 'en' : 'es');
  lang = languages.includes(pick) ? pick : 'es';
  applyDom();
}
